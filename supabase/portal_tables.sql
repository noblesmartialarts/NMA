-- Parent portal tables. Server functions only (service role): RLS on, no policies,
-- so the public/anon key can't read or write any of them.
create table if not exists public.portal_guardians (
  id text primary key,                 -- familyId:contactId
  email text not null,
  family_id text not null,
  name text,
  student_ids jsonb,                   -- null = all kids in the family
  enabled boolean not null default true,
  revoked_after timestamptz,           -- sessions issued before this are rejected
  invited_at timestamptz,
  last_seen timestamptz,
  updated_at timestamptz not null default now()
);
create index if not exists portal_guardians_email on public.portal_guardians (email);

create table if not exists public.portal_views (
  id text primary key,                 -- family id
  data jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.portal_inbox (
  id bigint generated by default as identity primary key,
  family_id text not null,
  email text,
  kind text not null,
  student_id text,
  event_id text,
  payload jsonb not null default '{}'::jsonb,
  status text not null default 'new',
  created_at timestamptz not null default now(),
  handled_at timestamptz
);
create index if not exists portal_inbox_status on public.portal_inbox (status, created_at desc);

create table if not exists public.portal_codes (
  id text primary key,                 -- email
  code_hash text,
  expires_at timestamptz,
  attempts int not null default 0,
  sends jsonb not null default '[]'::jsonb
);

create table if not exists public.portal_links (
  id text primary key,                 -- sha256 of the link token
  email text not null,
  family_id text not null,
  expires_at timestamptz not null,
  uses int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.portal_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  email text,
  family_id text,
  event text not null,
  ip text
);
create index if not exists portal_log_at on public.portal_log (at desc);

alter table public.portal_guardians enable row level security;
alter table public.portal_views     enable row level security;
alter table public.portal_inbox     enable row level security;
alter table public.portal_codes     enable row level security;
alter table public.portal_links     enable row level security;
alter table public.portal_log       enable row level security;
